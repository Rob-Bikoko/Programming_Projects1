#Question 2a Largest smallest and sum of a list
#Create a list of 10 numbers and print the largest number, smallest number and total.
"""
   Step by step method
   Step 1. Store exactly 10 numerical values in a list.
   Step 2. Pass the list to max() to obtain the largest value.
   Step 3. Pass the list to min() to obtain the smallest value.
   Step 4. Pass the list to sum() to obtain the total of all values.

"""
numbers = [12, 7, 25, 3, 18, 10, 42, 6, 15, 9]

print("Largest number:", max(numbers))
print("Smallest number:", min(numbers))
print("Sum of all numbers:", sum(numbers))
